/**
 * Сан для сортировки списков — от высшего к низшему.
 *
 * `сан_церк_служение` в базе — свободный текст: 288 вариантов, с уточнениями
 * в скобках, через запятую и с опечатками. Поэтому сан приводится к первой
 * части строки (до скобки или запятой) и ищется по таблице разрядов.
 *
 * Порядок — церковная иерархия: патриарх, митрополит, архиепископ, епископ,
 * затем священство (протопресвитер, архимандрит, игумен, протоиерей,
 * иеромонах, иерей), диаконы, церковнослужители, монашествующие и миряне.
 * Внутри одного разряда список сортируется по алфавиту (см. ShowCards).
 */
const RANK_TIERS: { pattern: RegExp; score: number }[] = [
    { pattern: /патриарх/, score: 1000 },
    { pattern: /митрополит/, score: 900 },
    { pattern: /архиепископ/, score: 800 },
    { pattern: /епископ|архиерей/, score: 700 },
    { pattern: /протопресвитер/, score: 650 },
    { pattern: /схиархимандрит/, score: 620 },
    { pattern: /архимандрит/, score: 600 },
    { pattern: /схиигумен/, score: 550 },
    // «игумения» и «игуменья» тоже попадают сюда.
    { pattern: /игумен/, score: 500 },
    { pattern: /протоиерей/, score: 450 },
    { pattern: /иеросхимонах/, score: 430 },
    { pattern: /иеромонах/, score: 400 },
    { pattern: /священн|иерей|служитель культа|единоверческий/, score: 380 },
    { pattern: /протодиакон/, score: 350 },
    { pattern: /архидиакон/, score: 340 },
    { pattern: /иеродиакон/, score: 330 },
    { pattern: /иподиакон/, score: 300 },
    { pattern: /диакон/, score: 320 },
    { pattern: /псаломщик|псаломщица/, score: 280 },
    { pattern: /чтец|пономарь|алтарник|алтарница|дьячок|причетник|церковнослужитель/, score: 260 },
    {
        pattern: /монах|монахиня|инок|инокиня|послушник|послушница|насельник|насельница|схимник|схимница/,
        score: 240,
    },
    {
        pattern:
            /староста|ктитор|казначей|председатель|член|секретарь|регент|певч|просвирн|просфорн|звонарь|сторож|уборщица|трудник|прихожан|юродив|блаженн|князь|император|профессор|доктор|писатель|философ|архитектор|иконописец|миссионер|сестра милосердия/,
        score: 100,
    },
];

export function rankScore(rank: string | null | undefined): number {
    if (!rank) return 0;

    const primary = rank.toLowerCase().split('(')[0].split(',')[0].trim();

    for (const { pattern, score } of RANK_TIERS) {
        if (pattern.test(primary)) return score;
    }

    return 0;
}
