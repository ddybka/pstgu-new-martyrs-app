/**
 * Общие настройки виртуализации списков карточек: на главной, в календаре и в
 * поиске карточка одна и та же (см. `PersonCard`), и досоздаваться они должны
 * одинаково.
 */

/**
 * Сколько экранов карточек держать смонтированными (вместе с видимым): по
 * три в обе стороны. Шире не нужно: карточка без SwiftUI-хоста, создать её
 * заново дёшево, а узкое окно бережёт память в днях с сотней фотографий.
 */
export const CARD_LIST_WINDOW_SIZE = 7;

/**
 * Темп досоздания карточек.
 *
 * В «Подробном» виде карточка высокая и тяжёлая, и пачек по две за 80 мс
 * хватает, чтобы прокрутка шла без запинок. В «Кратком» карточка в разы ниже:
 * в окно их помещается втрое больше, и те же две за 80 мс не успевают за
 * пальцем — список оставляет пустые места и дёргается. Там пачки больше и
 * чаще.
 */
export function cardListBatch(compact: boolean) {
    return {
        initialNumToRender: compact ? 10 : 5,
        maxToRenderPerBatch: compact ? 10 : 2,
        updateCellsBatchingPeriod: compact ? 50 : 80,
        windowSize: CARD_LIST_WINDOW_SIZE,
    };
}
